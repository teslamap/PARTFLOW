import assert from 'node:assert/strict';
import {certificateFields,localVinDetails} from '../src/certificate.mjs';
import {searchExpanded,searchMatchesCity,EXPANSION_DELAY} from '../src/search-expansion.mjs';
import {usageStatus,metricValue} from '../scripts/usage-policy.mjs';
const text='VIN JTDBR32E720123456\nPlate AB-123-CD\nTOYOTA PRIUS\nMODEL YEAR: 2018\nOwner Private Name ID 12345678901';
const d=certificateFields(text,95);
assert.deepEqual(d,{vin:'JTDBR32E720123456',plate:'AB123CD',brand:'Toyota',model:'Prius',year:'2018',engine:'',trim:'',fuel:''});
assert.ok(Object.values(certificateFields(text,30)).every(v=>v===''));
assert.equal(certificateFields(text+'\nWBA12345678901234',90).vin,'','ambiguous VIN left blank');
assert.equal(certificateFields('Date of registration 2018-01-02',90).year,'');
assert.equal(localVinDetails('WBA12345678901234').brand,'BMW');
assert.equal(localVinDetails('UNKNOWN').brand,'');
const now=Date.now(),r={searchScope:'city',city:'თბილისი',status:'open',acceptedOfferId:null,createdAt:new Date(now-EXPANSION_DELAY).toISOString()};
assert.equal(searchExpanded(r,now-1),false);assert.equal(searchExpanded(r,now),true);
assert.equal(searchExpanded({...r,acceptedOfferId:'o'},now),false);
assert.equal(searchExpanded({...r,status:'closed'},now),false);
assert.equal(searchExpanded({...r,status:'hidden'},now),false);
assert.equal(searchExpanded({...r,createdAt:'invalid'},now),false);
assert.equal(searchExpanded({...r,createdAt:new Date(now).toISOString(),expandedAt:now},now),true);
assert.equal(searchExpanded({...r,chatReplies:3,viewedOffers:12},now),true);
assert.equal(searchMatchesCity(r,'ბათუმი',now-1),false);assert.equal(searchMatchesCity(r,'თბილისი',now-1),true);
assert.equal(searchMatchesCity({...r,searchScope:undefined},'ბათუმი',now-1),true);
for(const [used,expected] of [[0,'ok'],[79,'ok'],[80,'warning'],[100,'critical'],[NaN,'unknown'],[-1,'unknown']])assert.equal(usageStatus(used,100),expected);
assert.equal(usageStatus(0,0),'unknown');
