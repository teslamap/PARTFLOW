import assert from 'node:assert/strict';
import {Timestamp} from 'firebase/firestore';
import {requestFields,canExpand,TOW_CITIES,EXPAND_AFTER} from '../src/towing.mjs';
import {locateTowCustomer} from '../src/towing-location.mjs';
assert.deepEqual(await locateTowCustomer({getCurrentPosition(success,failure,options){assert.equal(options.timeout,15000);success({coords:{latitude:41.64,longitude:41.63}})}}),{lat:41.64,lng:41.63});
await assert.rejects(locateTowCustomer(null),/მიუწვდომელია/);
await assert.rejects(locateTowCustomer({getCurrentPosition(_success,failure){failure({code:1})}}),/წვდომა დაბლოკილია/);
await assert.rejects(locateTowCustomer({getCurrentPosition(_success,failure){failure({code:3})}}),/დრო ამოეწურა/);
const now=Date.now(),base={mode:'sos',city:'ბათუმი',destinationCity:'ქობულეთი',origin:'რუსთაველის 1',destination:'სერვისი',vehicle:'Toyota Prius 2015',condition:'rolls',phone:'+995555123456',notes:'',location:{lat:41.64,lng:41.63}};
assert.equal(requestFields(base,now).scope,'city');
assert.throws(()=>requestFields({...base,location:null},now));
assert.throws(()=>requestFields({...base,location:{lat:NaN,lng:41}},now));
assert.throws(()=>requestFields({...base,location:{lat:91,lng:41}},now));
assert.throws(()=>requestFields({...base,city:'OTHER'},now));
assert.throws(()=>requestFields({...base,condition:'unknown'},now));
assert.throws(()=>requestFields({...base,phone:'555'},now));
assert.throws(()=>requestFields({...base,notes:'x'.repeat(1001)},now));
const intercity={...base,mode:'intercity',pickupAt:new Date(now+3600000).toISOString()};
assert.equal(requestFields(intercity,now).location,null);
assert.equal(requestFields(intercity,now).scope,'all');
assert.throws(()=>requestFields({...intercity,pickupAt:new Date(now-1).toISOString()},now));
assert.throws(()=>requestFields({...intercity,pickupAt:''},now));
const r={mode:'sos',status:'searching',scope:'city',createdAt:Timestamp.fromMillis(now-EXPAND_AFTER)};
assert.equal(canExpand(r,now-1),false);assert.equal(canExpand(r,now),true);
for(const patch of [{status:'offered'},{status:'confirmed'},{scope:'all'},{mode:'intercity'}])assert.equal(canExpand({...r,...patch},now),false);
assert.equal(new Set(TOW_CITIES).size,TOW_CITIES.length);
console.log('Towing validation and exact expansion boundary passed');
