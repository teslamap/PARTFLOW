import assert from 'node:assert/strict';
import {activeQuote,expiresAt,totalPrice,priceStats,demandStats,repeatFields,responseSeconds} from '../src/marketplace-policy.mjs';
import {buildNotifications} from '../src/notifications.mjs';
const createdAt='2026-11-20T00:00:00Z',now=Date.parse(createdAt);
assert.equal(activeQuote({createdAt,validDays:1},now+86400000-1),true);
assert.equal(activeQuote({createdAt,validDays:1},now+86400000),false);
assert.equal(activeQuote({createdAt},now+999999999),true);
assert.equal(expiresAt({createdAt,validDays:3,renewedAt:{toMillis:()=>now+86400000}}),now+4*86400000);
assert.equal(totalPrice({price:100,serviceAvailable:true,servicePrice:20}),120);
assert.deepEqual(priceStats([{price:20},{price:100},{price:0}]),{count:2,min:20,max:100,average:60});
assert.equal(priceStats([]),null);
assert.deepEqual(demandStats([{brand:'Toyota',model:'Prius',category:'x',status:'open'},{brand:'Toyota',model:'Prius',category:'x',status:'closed'},{brand:'Toyota',model:'Prius',category:'x',status:'hidden'}]),[['Toyota · Prius · x',2]]);
assert.equal(repeatFields({id:'old',photos:['x'],ownerId:'a',part:'part',budget:50}).part,'part');
assert.equal(Object.hasOwn(repeatFields({photos:['x']}),'photos'),false);
assert.equal(responseSeconds({createdAt:now},{createdAt:now+2000}),2);
const r={id:'r',ownerId:'buyer',status:'open',brand:'Toyota',model:'Prius',category:'x',city:'თბილისი',part:'test',createdAt};
const o={id:'o',requestId:'r',ownerId:'buyer',shopId:'shop',price:120,createdAt};
const c={id:'o',offerId:'o',requestId:'r',ownerId:'buyer',shopId:'shop',status:'pending',price:100,version:2,updatedAt:createdAt};
assert.ok(buildNotifications({uid:'buyer',requests:[r],offers:[o],confirmations:[c],marketplace:true}).some(n=>n.id==='price_o_2'));
assert.ok(!buildNotifications({uid:'buyer',requests:[{...r,status:'closed'}],offers:[o],confirmations:[c],marketplace:true}).some(n=>n.id==='price_o_2'));
assert.ok(!buildNotifications({uid:'stranger',requests:[r],offers:[o],confirmations:[c],marketplace:true}).some(n=>n.id==='price_o_2'));
console.log('PASS marketplace policy, expiry, price comparison, request cloning and price notifications');
